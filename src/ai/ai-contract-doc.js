// ai-contract-doc.js
//
// The "README-for-AI.md" contract doc (AI-readable layer, Phase 3). Pure, no
// I/O: returns a versioned markdown string from an in-code template. Wren writes
// it into the notes-folder root once per session when missing or version-stale
// (see app-controller). It is Wren-managed and excluded from the notes list.
//
// The read-side content is shipped VERBATIM from the Phase 3 spec — do not
// paraphrase or restructure it. Only two tokens are substituted: the version
// marker and the generatedAt timestamp.
//
// v2 rewrote the "Writing" section only. v1 told every AI reading a user's
// vault that Wren had no write-back channel and that `_inbox/` was reserved for
// a future version. Both stopped being true once the `_inbox/` staging channel
// shipped (FileSystemAdapter/TauriFsAdapter INBOX_DIR, the Inbox section in the
// app, and the wren-mcp server that writes into it), so the doc was actively
// telling agents not to use a supported feature.

export const AI_CONTRACT_DOC_NAME = 'README-for-AI.md';

// Bump when the contract content changes. app-controller rewrites the on-disk
// doc when its first line's `<!-- wren-ai-contract v<N> -->` marker is stale.
export const AI_CONTRACT_VERSION = 2;

/**
 * Build the README-for-AI.md contents. The first line is always
 * `<!-- wren-ai-contract v<AI_CONTRACT_VERSION> -->` (the staleness marker).
 *
 * @returns {string} markdown
 */
export function buildAiContractDoc() {
  const generatedAt = new Date().toISOString();
  return `<!-- wren-ai-contract v${AI_CONTRACT_VERSION} -->
# Reading these notes (for AI assistants)

This folder is a **Wren** notes library. Every note is a plain UTF-8 Markdown file with YAML frontmatter. This document tells an AI agent how to read the library efficiently and correctly. It is auto-generated by Wren — do not edit by hand.

Generated: ${generatedAt}

## How to read (do this, in order)

1. **Read \`.wren-index.json\` first.** It is the catalog of every note with metadata — read it once instead of opening every \`.md\` file. Its shape is documented below.
2. **Open individual notes by \`path\`.** Each index entry has a \`path\` relative to this folder root. Read a note's full content only when you actually need its body.
3. **Do not crawl every file.** For "what notes exist / find notes about X", use the index. Only fetch bodies for the specific notes you need. This keeps you inside your context budget.
4. **Skip reserved files.** Files managed by Wren are not user notes — never treat them as notes: \`.wren-index.json\`, \`_index.md\`, \`README-for-AI.md\`, and \`tasks.md\` (reserved). Anything under a \`_inbox/\` subfolder is staging, not the main corpus.
5. **Check freshness.** The index has a top-level \`generatedAt\`; each entry has \`updated\`. Wren regenerates the index on every save, so it is normally current. If a note file's on-disk modified time is newer than its index \`updated\`, that entry may be stale — re-read the file.

## \`.wren-index.json\` schema

Top-level object:

| Field | Type | Meaning |
|---|---|---|
| \`schemaVersion\` | number | Index schema version. Currently 1. Adapt to changes; do not assume future shape. |
| \`generatedAt\` | string (ISO-8601) | When Wren last regenerated the whole index. |
| \`backend\` | string | \`"fs"\` (local disk) or \`"drive"\` (Google Drive). |
| \`count\` | number | Number of notes. |
| \`notes\` | array | One entry per note, sorted by \`updated\` descending. |

Each \`notes[]\` entry:

| Field | Type | Meaning |
|---|---|---|
| \`wrenId\` | string | Stable note id (\`wren-...\`). The durable identifier — use this to refer to a note; it survives renames. |
| \`storageId\` | string | Backend storage id (filename on FS, file id on Drive). |
| \`path\` | string | Path to the note file relative to this folder root. Use this to open the note. |
| \`file\` | string | Human-readable filename. |
| \`title\` | string | Note title. |
| \`summary\` | string | Short abstract. Sufficient for search-result display — prefer it over reading the body when you just need the gist. May be empty. |
| \`due\` | string | ISO date/timestamp, or empty. |
| \`tags\` | string[] | Namespaced tags, e.g. \`status:todo\`, \`priority:high\`, \`person:adam\`. |
| \`color\` | string | Wren note color id. |
| \`created\` | string (ISO-8601) | Creation time. |
| \`updated\` | string (ISO-8601) | Last-modified time. |
| \`contentHash\` | string | Change-detection token (FS: \`sha256-<hex>\` of body; Drive: revision id). Changes when the body changes. |

## Note file format

Each \`.md\` note is YAML frontmatter then a Markdown body:

---
id: wren-k3p9x2m7q1za
title: "My note title"
created: 2026-06-01T14:30:00Z
modified: 2026-06-01T14:30:00Z
color: amber
due: 2026-06-10
summary: "One or two sentence abstract of the note."
tags: ["status:todo", "project:wren"]
---

Markdown body...

The frontmatter \`id\` equals the index \`wrenId\`. \`due\`, \`summary\`, and \`tags\` are optional and only present when set. \`tags\` use a \`namespace:value\` convention (the part before the first colon is the namespace); un-namespaced tags are allowed.

## Writing

Wren **does** provide an AI write-back channel, and it is the only sanctioned way to change anything in this folder.

- **Do not write to these files directly.** Editing or creating \`.md\` files behind Wren's back races the app's own saves and its index regeneration, and it leaves no record of what an AI changed.
- **Go through the Wren MCP server** (\`wren-mcp\`) when the user has it installed. Alongside the read tools it exposes write tools that create, update, append to, retag, soft-delete, restore, and promote notes, and it applies the safety rules below on every write.
- **\`_inbox/\` is the live staging area**, not a future plan. A note created through the write-back channel lands in \`_inbox/\` by default; the user reviews it in Wren's Inbox and either promotes it into the main notes or discards it. Nothing an AI creates joins the corpus on its own.

The write path is guarded, and the guards are worth knowing because they change how you should sequence calls:

- **Read first.** \`wren_read_note\` returns a \`contentHash\`. Every modify tool requires it back as \`expected_content_hash\`; if the note changed on disk since you read it, the write is rejected as a conflict rather than blindly overwriting. Re-read and retry.
- **Preview with \`dry_run\`.** The modify tools return a diff without writing when \`dry_run: true\`.
- **Destructive actions need \`confirm: true\`** - soft-deleting a note, and promoting a staged draft into the live notes.
- **Deletes are reversible.** A soft-deleted note is moved to \`.trash/\`, never removed; \`wren_restore_note\` brings it back by id.
- **Everything stays inside this folder.** Paths that escape the notes root via \`..\` or an absolute path are rejected.
- **Provenance is stamped.** Notes written through the channel carry \`created_by\`, \`last_edited_by\` and \`last_edited\` frontmatter, so an AI-authored or AI-edited note stays distinguishable from a human one. Preserve those fields.
`;
}
